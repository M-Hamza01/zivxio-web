#!/usr/bin/env node
/**
 * Refreshes rating / review-count / install-count data for each app from
 * its public Google Play Store listing, and writes the result to
 * src/data/app-stats.json — which src/lib/site-config.ts reads at build
 * time and merges over the hand-written fallback values.
 *
 * WHY THIS EXISTS
 * There is no official, free API that returns the aggregate rating and
 * install-count figures shown on a Play Store listing page:
 *   - The official Play Developer API (androidpublisher v3) can list raw
 *     individual reviews for apps you own, but doesn't expose the
 *     aggregate rating or install count.
 *   - Install counts specifically are never exposed via any Google API —
 *     only a rounded public range is shown on the listing page itself.
 * This script instead uses the `google-play-scraper` npm package, which
 * parses the same public listing page anyone can visit in a browser. It's
 * free and has no API key, but it's unofficial: it can break if Google
 * changes the page's markup, and it should be treated as "best effort."
 *
 * BEST PRACTICES THIS SCRIPT FOLLOWS
 *   1. Never called from a page request or from client-side code — it's an
 *      offline/build-time data-refresh step only (run manually, or on a
 *      schedule via CI; see .github/workflows/update-app-stats.yml).
 *   2. Failures are per-app and non-destructive: if a fetch fails, the
 *      previous cached value for that app is kept rather than being
 *      overwritten with zeros.
 *   3. Writes go to a small, version-controlled JSON cache
 *      (src/data/app-stats.json) rather than mutating site-config.ts
 *      directly, so the site's real copy (descriptions, features, FAQs)
 *      can never be clobbered by an automated run — only the three
 *      numeric fields are ever touched.
 *   4. Exits non-zero only when every single app failed (a systemic
 *      problem), so CI can flag that without failing loudly on one flaky
 *      request among several apps.
 *
 * USAGE
 *   npm run update-stats
 *
 * (Requires the `google-play-scraper` package — see scripts/README.md for
 * the one-time setup if it isn't already a project dependency.)
 */

import { writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import gplay from "google-play-scraper";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_PATH = path.join(__dirname, "../src/data/app-stats.json");

// slug -> Play Store package name (appId). Keep this in sync with the
// playStoreUrl entries in src/lib/site-config.ts — add a line here whenever
// a new app gets a Play Store listing.
// slug -> app configuration
const APPS = {
  "nust-one": { appId: "com.zivxio.nustone", country: "pk" },
  billcheck: { appId: "com.zivxio.billcheck", country: "us" },
};

const REQUEST_DELAY_MS = 1500; // be polite — space requests out, no burst hits

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// Match the site's existing "300+" / "New" copy style rather than the raw
// Play Store range (which looks like "100,000+" and reads oddly for a
// small app).
function formatInstalls(minInstalls) {
  if (!minInstalls || minInstalls <= 0) return "New";
  return `${minInstalls}+`;
}

async function loadExisting() {
  try {
    const raw = await readFile(DATA_PATH, "utf8");
    const parsed = JSON.parse(raw);
    return { updatedAt: parsed.updatedAt ?? null, apps: parsed.apps ?? {} };
  } catch {
    // First run, or the file is missing/corrupt — start from empty and
    // let the fetch below populate it.
    return { updatedAt: null, apps: {} };
  }
}

async function main() {
  const existing = await loadExisting();
  const next = {
    updatedAt: new Date().toISOString(),
    note:
      "Auto-generated by scripts/update-app-stats.mjs — do not hand-edit for long, your changes will be overwritten on the next run. See scripts/README.md.",
    apps: { ...existing.apps },
  };

  const slugs = Object.entries(APPS);
  let failures = 0;

  for (let i = 0; i < slugs.length; i++) {
    const [slug, appConfig] = slugs[i];
    const previous = existing.apps[slug] ?? {};

    try {
      const info = await gplay.app({ 
        appId: appConfig.appId, 
        country: appConfig.country, 
        lang: "en" 
      });

      // IMPORTANT: score/ratings can legitimately be `undefined` here, and
      // that's not a fetch failure — Google Play simply doesn't render a
      // public star rating on the listing page for apps that don't yet
      // have enough reviews (it shows "Not enough ratings" instead of a
      // number). Only overwrite a field if we actually got a value for it;
      // otherwise keep whatever was cached before, so one missing field on
      // a low-traffic app doesn't wipe out a real number with a false "0".
      const missing = [];
      const rating =
        info.score != null ? Math.round(info.score * 10) / 10 : (missing.push("rating"), previous.rating ?? 0);
      const ratingCount =
        info.ratings != null ? info.ratings : (missing.push("ratingCount"), previous.ratingCount ?? 0);
      const installs =
        info.minInstalls != null
          ? formatInstalls(info.minInstalls)
          : (missing.push("installs"), previous.installs ?? "New");

      next.apps[slug] = { rating, ratingCount, installs };

      const note = missing.length
        ? ` (Play Store isn't publicly showing ${missing.join(" or ")} yet — kept cached value)`
        : "";
      console.log(`\u2713 ${slug}: ${rating}\u2605, ${ratingCount} ratings, ${installs} installs${note}`);
    } catch (err) {
      failures++;
      console.error(
        `\u2717 ${slug}: fetch failed (${err.message}) — keeping previous cached value`
      );
      // Deliberately leave next.apps[slug] as whatever it already was
      // (from `existing`) rather than writing zeros over good data.
    }

    // Small delay between requests so a run over several apps doesn't look
    // like a burst of automated traffic against the Play Store.
    if (i < slugs.length - 1) {
      await sleep(REQUEST_DELAY_MS);
    }
  }

  await writeFile(DATA_PATH, JSON.stringify(next, null, 2) + "\n");
  console.log(`\nWrote ${DATA_PATH}`);

  if (failures === slugs.length) {
    // Every app failed — almost certainly a network or library problem
    // rather than a per-app fluke. Exit non-zero so CI surfaces it instead
    // of silently "succeeding" with entirely stale data.
    console.error("\nAll fetches failed — leaving app-stats.json untouched in spirit (no fresh data written) and flagging this run as failed.");
    process.exitCode = 1;
  }
}

main();
